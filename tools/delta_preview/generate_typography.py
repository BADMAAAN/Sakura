"""Build native-size 4-bit AA text from installed Segoe fonts; no font downloads.

Regeneration requires the same font files and Pillow. Font SHA256s are recorded
in the generated header so a changed Windows font cannot silently change assets.
"""
from pathlib import Path
import hashlib
import math
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
SUPERSAMPLE = 4
FONT_DIR = Path("C:/Windows/Fonts")
FACES = (("seguisb.ttf", 14, 14, 18), ("segoeui.ttf", 12, 11, 15), ("seguisb.ttf", 25, 25, 30))
CODEPOINTS = tuple(range(32, 127)) + tuple(range(160, 256)) + tuple(range(0x400, 0x460))


def generate():
    atlas = []
    metrics = []
    provenance = []
    for filename, size, baseline, line_height in FACES:
        path = FONT_DIR / filename
        provenance.append(f"// {filename}: {hashlib.sha256(path.read_bytes()).hexdigest()}; {size}px, line {line_height}px")
        font = ImageFont.truetype(str(path), size * SUPERSAMPLE)
        glyphs = []
        for codepoint in CODEPOINTS:
            character = chr(codepoint)
            left, top, right, bottom = font.getbbox(character, anchor="ls")
            left, top = math.floor(left / SUPERSAMPLE), math.floor(top / SUPERSAMPLE)
            right, bottom = math.ceil(right / SUPERSAMPLE), math.ceil(bottom / SUPERSAMPLE)
            width, height = right - left, bottom - top
            # One pixel of tracking separates small technical labels without scaling pixels.
            advance = round(font.getlength(character) / SUPERSAMPLE) + 1
            offset = len(atlas) * 2
            if width and height:
                image = Image.new("L", (width * SUPERSAMPLE, height * SUPERSAMPLE))
                ImageDraw.Draw(image).text((-left * SUPERSAMPLE, -top * SUPERSAMPLE), character, font=font, fill=255, anchor="ls")
                image = image.resize((width, height), Image.Resampling.LANCZOS)
                values = [(value * 15 + 127) // 255 for value in image.tobytes()]
                if len(values) & 1:
                    values.append(0)
                atlas.extend((values[i] << 4) | values[i + 1] for i in range(0, len(values), 2))
            glyphs.append((offset, left, baseline + top, width, height, advance))
        metrics.append(glyphs)
    # Keep the entire font budget visible and bounded before a firmware build.
    footprint = len(atlas) + len(CODEPOINTS) * 2 + 3 * len(CODEPOINTS) * 12
    if footprint > 80000:
        raise ValueError(f"Typography uses {footprint} bytes, over the 80000-byte budget")
    lines = ["#pragma once", "#include <stdint.h>", "// Generated by tools/delta_preview/generate_typography.py; 4x supersampling, packed 4-bit coverage."]
    lines.extend(provenance)
    lines += [f"// Total conservative flash footprint: {footprint} bytes.", "namespace delta { namespace typeface { namespace data {", "struct Glyph { uint32_t offset; int8_t x, y; uint8_t width, height, advance; };", f"static const unsigned GlyphCount = {len(CODEPOINTS)};"]

    def declaration(type_name, name, shape, values):
        lines.extend(["#if defined(ARDUINO) && defined(FLUX_DELTA_BUILD)", "extern", "#else", "static", "#endif", f"const {type_name} {name}{shape}", "#if !defined(ARDUINO) || !defined(FLUX_DELTA_BUILD) || defined(DELTA_TYPOGRAPHY_IMPLEMENTATION)", "= {"])
        lines.extend(values)
        lines.extend(["}", "#endif", ";"])

    declaration("uint16_t", "codepoints", "[GlyphCount]", ["    " + ",".join(map(str, CODEPOINTS[i:i + 24])) + "," for i in range(0, len(CODEPOINTS), 24)])
    rows = []
    for glyphs in metrics:
        rows.append("    {")
        rows.extend("        {" + ",".join(map(str, glyph)) + "}," for glyph in glyphs)
        rows.append("    },")
    declaration("Glyph", "glyphs", "[3][GlyphCount]", rows)
    declaration("uint8_t", "coverage", f"[{len(atlas)}]", ["    " + ",".join(map(str, atlas[i:i + 28])) + "," for i in range(0, len(atlas), 28)])
    lines.append("} } } // namespace delta::typeface::data")
    destination = ROOT / "include/delta/typography_data.h"
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(CODEPOINTS)} glyphs x 3 faces, {len(atlas)} coverage bytes, {footprint} total flash bytes")


if __name__ == "__main__":
    generate()
